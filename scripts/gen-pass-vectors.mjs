/**
 * Generate cross-language pass vectors.
 *
 * The guard app reimplements pass verification in Dart. Two implementations of one
 * signature format will drift — a changed field order, a different base64 variant, a
 * timestamp in milliseconds instead of seconds — and the failure surfaces at a gate at
 * 7am, on a device with no network, in front of a queue.
 *
 * So the TypeScript signer emits vectors here and the Dart suite verifies them. A
 * divergence fails the Dart build instead.
 *
 * Deterministic: a fixed keypair and fixed timestamps, so the committed file only
 * changes when the format genuinely changes. Regenerate with:
 *
 *     node scripts/gen-pass-vectors.mjs
 */

import { createPrivateKey, createPublicKey, sign as edSign } from "node:crypto";
import { writeFileSync } from "node:fs";

const PASS_VERSION = "v1";

/**
 * A fixed test keypair. Test-only and safe to commit — it signs nothing real, and a
 * generated-per-run key would make the vectors churn on every regeneration, hiding
 * whether the format actually changed.
 */
const PRIVATE_PEM = `-----BEGIN PRIVATE KEY-----
MC4CAQAwBQYDK2VwBCIEIJ1sZ4d0nQZ0Zx0nQZ0Zx0nQZ0Zx0nQZ0Zx0nQZ0Zx0n
-----END PRIVATE KEY-----
`;

function canonical(p) {
  return Buffer.from(
    [
      PASS_VERSION,
      p.passId,
      p.societyId,
      p.unitId,
      String(Math.floor(p.validFrom / 1000)),
      String(Math.floor(p.validTo / 1000)),
      String(p.maxUses),
      p.visitorHash,
      String(p.keyVersion),
    ].join("|"),
    "utf8",
  );
}

function signPass(payload, privatePem) {
  const key = createPrivateKey(privatePem);
  const body = canonical(payload);
  const signature = edSign(null, body, key);
  return `${body.toString("base64url")}.${signature.toString("base64url")}`;
}

function rawPublic(privatePem) {
  const der = createPublicKey(privatePem).export({ type: "spki", format: "der" });
  return der.subarray(der.length - 32).toString("base64url");
}

const publicB64 = rawPublic(PRIVATE_PEM);

// Fixed instants so the file is stable.
